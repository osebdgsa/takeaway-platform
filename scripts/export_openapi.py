"""Write the generated OpenAPI schema to ``openapi.json``.

The schema is generated by FastAPI from the routes and Pydantic models, so this
file is a build artefact — never edit it by hand. Regenerate with::

    make openapi

``tests/test_openapi.py`` fails if the committed file drifts from the app.
"""

import json
import sys
from pathlib import Path

from app.main import app

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "openapi.json"


def render() -> str:
    return json.dumps(app.openapi(), indent=2, sort_keys=True) + "\n"


def main() -> int:
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
